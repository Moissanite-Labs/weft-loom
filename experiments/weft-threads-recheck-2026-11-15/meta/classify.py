#!/usr/bin/env python3
"""Count the review findings by kind, source and direction.

Reads findings.json (findings from the experiments index, the reruns in this
record and the sentence audit of the weft README and papers) and prints the
tables used in review-meta.md. The sentence audit rows are read from
../runtime/rows.tsv, where verdict X is a mismatch and N is no evidence.

Usage: python3 classify.py
"""
import csv
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
data = json.loads((HERE / "findings.json").read_text())
F = data["findings"]
kinds = list(data["kinds"])
for f in F:
    if f["kind"] not in kinds or f["dir"] not in ("over", "under", "none", "unknown"):
        raise SystemExit(f"bad finding: {f}")

print(f"findings in findings.json: {len(F)}")
print("\nby kind and source")
srcs = ["index", "repro", "colony", "prs", "admission", "runtime", "tf"]
print(f"{'kind':10s} " + " ".join(f"{s:>9s}" for s in srcs) + f" {'total':>6s}")
for k in kinds:
    row = [sum(1 for f in F if f["kind"] == k and f["src"] == s) for s in srcs]
    print(f"{k:10s} " + " ".join(f"{v:9d}" for v in row) + f" {sum(row):6d}")
tot = [sum(1 for f in F if f["src"] == s) for s in srcs]
print(f"{'total':10s} " + " ".join(f"{v:9d}" for v in tot) + f" {sum(tot):6d}")

d = Counter(f["dir"] for f in F)
directed = d["over"] + d["under"]
print(f"\ndirection, records and programs: over {d['over']}, under {d['under']}, none {d['none']}, unknown {d['unknown']}")
print(f"share of directed findings that claim more than the evidence: {d['over']}/{directed}")

recs = Counter(f["rec"] for f in F if f["src"] == "index")
print(f"\nindex records with at least one finding: {len(recs)}")

rows_path = HERE.parent / "runtime" / "rows.tsv"
if rows_path.exists():
    rows = list(csv.DictReader(rows_path.open(), delimiter="\t"))
    v = Counter(r["verdict"] for r in rows)
    prob = [r for r in rows if r["verdict"] in ("X", "N")]
    dd = Counter(r["direction"] for r in prob)
    print(f"\nsentence audit of weft README and Papers 0 to 2: {len(rows)} sentences")
    print(f"match {v['M']}, regenerated by CI {v['CI']}, mismatch {v['X']}, no evidence {v['N']}")
    print(f"direction of the {len(prob)} problem sentences: less {dd['less']}, more {dd['more']}, neither {dd['neither']}")
    by_doc = Counter(r["doc"] for r in prob)
    print("problem sentences by document:", dict(sorted(by_doc.items())))
else:
    print("\n(rows.tsv not present)")
