import random

random.seed(42)
def int_to_word(n):
    s = []
    for _ in range(5):
        s.append(chr(97 + (n % 26)))
        n //= 26
    return "".join(s)

vocab = [int_to_word(i) for i in range(5000)]
weights = [1.0 / (i + 1) ** 0.75 for i in range(len(vocab))]
words = random.choices(vocab, weights=weights, k=250000)
# Inject an exact tie in top 10 between " tiedb" and " tieda"
words.extend(["tiedb"] * 4000)
words.extend(["tieda"] * 4000)
random.shuffle(words)

punct = [" ", " ", " ", " ", ", ", ". ", "! ", "? ", "\n", " - ", "; ", ": ", "\n"]
chunk = "".join((w.capitalize() if i % 7 == 0 else (w.upper() if i % 23 == 0 else w)) + punct[i % len(punct)] for i, w in enumerate(words))
repeats = (20 * 1024 * 1024) // len(chunk)
data = chunk * repeats
# pad with uncommon unique words to exact 20MB if needed, or keep exact repeats so tie is preserved!
pad_len = 20 * 1024 * 1024 - len(data)
data += (" " + "zzzzz " * (pad_len // 6 + 1))[:pad_len]
with open("input20m.txt", "w") as f:
    f.write(data)
print("Generated bytes:", len(data))
